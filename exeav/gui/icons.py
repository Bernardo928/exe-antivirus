@lru_cache(maxsize=512)
def pixmap(name: str, color: str = "#e6edf3", size: int = 20, stroke: float = 2.0) -> QPixmap:
    body = PATHS.get(name, PATHS["info"])
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
           f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>')
    r = QSvgRenderer(QByteArray(svg.encode()))
    pm = QPixmap(size * 2, size * 2)
    pm.fill(Qt.transparent)
    p = QPainter(pm)
    p.setRenderHint(QPainter.Antialiasing)
    r.render(p)
    p.end()
    pm.setDevicePixelRatio(2.0)
    return pm


def icon(name: str, color: str = "#e6edf3", size: int = 20) -> QIcon:
    ic = QIcon()
    ic.addPixmap(pixmap(name, color, size))
    return ic


def app_icon_pixmap(size: int = 256, color_top: str = "#4aa3ff", color_bottom: str = "#1d5fd1") -> QPixmap:
    """Ícone do aplicativo: escudo com gradiente e marca de verificação."""
    pm = QPixmap(size, size)
    pm.fill(Qt.transparent)
    p = QPainter(pm)
    p.setRenderHint(QPainter.Antialiasing)
    s = size / 24.0
    path = QPainterPath()
    path.moveTo(12 * s, 22.5 * s)
    path.cubicTo(12 * s, 22.5 * s, 20.5 * s, 18.5 * s, 20.5 * s, 12 * s)
    path.lineTo(20.5 * s, 4.6 * s)
    path.lineTo(12 * s, 1.5 * s)
    path.lineTo(3.5 * s, 4.6 * s)
    path.lineTo(3.5 * s, 12 * s)
    path.cubicTo(3.5 * s, 18.5 * s, 12 * s, 22.5 * s, 12 * s, 22.5 * s)
    g = QLinearGradient(0, 0, 0, size)
    g.setColorAt(0, QColor(color_top))
    g.setColorAt(1, QColor(color_bottom))
    p.fillPath(path, g)
    pen = QPen(QColor("white"), 2.3 * s, Qt.SolidLine, Qt.RoundCap, Qt.RoundJoin)
    p.setPen(pen)
    chk = QPainterPath()
    chk.moveTo(8.2 * s, 12.2 * s)
    chk.lineTo(11 * s, 15 * s)
    chk.lineTo(16 * s, 9.3 * s)
    p.drawPath(chk)
    p.end()
    return pm


def app_icon() -> QIcon:
    ic = QIcon()
    for sz in (16, 24, 32, 48, 64, 128, 256):
        ic.addPixmap(app_icon_pixmap(sz))
    return ic


def status_icon(ok: bool) -> QIcon:
    return QIcon(app_icon_pixmap(64) if ok else app_icon_pixmap(64, "#ff7a7f", "#c4262e"))


def shape_rect(w: float, h: float) -> QRectF:
    return QRectF(0, 0, w, h)
